import {
  Body,
  Controller,
  Delete,
  Get,
  Param,
  ParseIntPipe,
  Patch,
  Post,
  Query,
} from '@nestjs/common';
import { InvoiceItemService } from './invoiceItem.service';
import { CreateInvoiceItemDto } from './dto/create-invoiceItem.dto';
@Controller('invoice-items')
export class InvoiceItemController {
  constructor(private readonly service: InvoiceItemService) {}
  @Post() create(@Body() dto: CreateInvoiceItemDto) {
    return this.service.create(dto);
  }
  @Get() findAll(@Query() query: any) {
    return this.service.findAll(query);
  }
  @Get(':id') findOne(@Param('id', ParseIntPipe) id: number) {
    return this.service.findOne(id);
  }
  @Patch(':id') update(@Param('id', ParseIntPipe) id: number, @Body() dto: any) {
    return this.service.update(id, dto);
  }
  @Delete(':id') remove(@Param('id', ParseIntPipe) id: number) {
    return this.service.remove(id);
  }
}
